import { useEffect, useMemo, useState } from "react";
import { aggregate, CandleChart, DepthChart, Sparkline } from "./Charts";
import { book, buyingPower, candles, check, equity, holdings, LIMITS, newAccount, place, series, SYMBOLS, type Account, type Order, type OrderRec, type Sym } from "./sim";

const WARM = 200; // ticks of history already "played" when the demo opens
const usd = (n: number) => n.toLocaleString("en-US", { style: "currency", currency: "USD" });
const signed = (n: number) => `${n >= 0 ? "+" : "−"}${usd(Math.abs(n))}`;
const pnlClass = (n: number) => (Math.abs(n) < 0.005 ? "" : n > 0 ? "up" : "dn");

// Scripted sample run: one limit buy per stock at the third ask level, generated by this site's own simulator.
const sample = (() => {
  const marks = Object.fromEntries(SYMBOLS.map((s) => [s, series(s)[WARM]])) as Record<Sym, number>;
  let acct = newAccount();
  return SYMBOLS.map((s, i) => {
    const b = book(s, WARM);
    const o: Order = { side: "buy", type: "limit", sym: s, qty: 20, limit: b.asks[2].price };
    const r = place(acct, o, b, WARM, marks, i + 1);
    acct = r.acct;
    return r.rec;
  });
})();

const TFS = [["1D", 1], ["5D", 5], ["21D", 21]] as const;
const RANGES = [["60", 60], ["120", 120], ["All", 9999]] as const;
type Tab = "positions" | "orders" | "executions" | "sample";

function Seg<T extends string | number>({ name, label, value, opts, onChange }: { name: string; label: string; value: T; opts: readonly (readonly [string, T])[]; onChange: (v: T) => void }) {
  return (
    <div role="radiogroup" aria-label={label} className="seg">
      {opts.map(([text, v]) => (
        <label key={text} className={v === value ? "on" : ""}><input type="radio" name={name} checked={v === value} onChange={() => onChange(v)} aria-label={text} />{text}</label>
      ))}
    </div>
  );
}

export function Demo() {
  const [sym, setSym] = useState<Sym>("AAPL");
  const [tick, setTick] = useState(WARM);
  const [playing, setPlaying] = useState(false);
  const [speed, setSpeed] = useState(1);
  const [acct, setAcct] = useState<Account>(newAccount);
  const [recs, setRecs] = useState<OrderRec[]>([]);
  const [tf, setTf] = useState(1);
  const [range, setRange] = useState(60);
  const [showSma, setShowSma] = useState(true);
  const [tab, setTab] = useState<Tab>("positions");
  const [form, setForm] = useState({ side: "buy" as Order["side"], type: "market" as Order["type"], qty: "5", limit: "" });

  const all = useMemo(() => Object.fromEntries(SYMBOLS.map((s) => [s, series(s)])) as Record<Sym, number[]>, []);
  const ohlc = useMemo(() => candles(sym, all[sym]), [sym, all]);
  const marks = useMemo(() => Object.fromEntries(SYMBOLS.map((s) => [s, all[s][tick]])) as Record<Sym, number>, [all, tick]);
  const closes = all[sym];
  const end = closes.length - 1;
  const bk = useMemo(() => book(sym, tick, closes), [sym, tick, closes]);
  const bars = useMemo(() => aggregate(ohlc.slice(0, tick + 1), tf).slice(-range), [ohlc, tick, tf, range]);

  useEffect(() => {
    if (!playing) return;
    const id = setInterval(() => setTick((t) => (t >= end ? (setPlaying(false), t) : t + 1)), 700 / speed);
    return () => clearInterval(id);
  }, [playing, end, speed]);

  const qty = Number(form.qty);
  const order: Order = { side: form.side, type: form.type, sym, qty, limit: form.type === "limit" ? Number(form.limit) : undefined };
  const refPx = form.type === "limit" && Number(form.limit) > 0 ? Number(form.limit) : form.side === "buy" ? bk.asks[0].price : bk.bids[0].price;
  const preCheck = check(acct, order, bk, marks);
  const last = recs[0];

  const send = (e: React.FormEvent) => {
    e.preventDefault();
    const r = place(acct, order, bk, tick, marks, recs.length + 1);
    setAcct(r.acct);
    setRecs([r.rec, ...recs]);
  };
  const reset = () => { setTick(WARM); setAcct(newAccount()); setRecs([]); setPlaying(false); };

  const eq = equity(acct, marks), hold = holdings(acct);
  const rows = SYMBOLS.filter((s) => hold[s]?.qty).map((s) => {
    const h = hold[s]!, mv = h.qty * marks[s];
    return { s, qty: h.qty, avg: h.cost / h.qty, mv, upl: mv - h.cost };
  });
  const unreal = rows.reduce((t, r) => t + r.upl, 0), mvTotal = rows.reduce((t, r) => t + r.mv, 0);
  const realized = SYMBOLS.reduce((t, s) => t + (hold[s]?.realized ?? 0), 0);
  const total = eq - LIMITS.startCash;
  const maxQ = Math.max(...bk.bids.map((l) => l.qty), ...bk.asks.map((l) => l.qty));
  const cumB = bk.bids.reduce<number[]>((a, l) => [...a, (a.at(-1) ?? 0) + l.qty], []);
  const cumA = bk.asks.reduce<number[]>((a, l) => [...a, (a.at(-1) ?? 0) + l.qty], []);
  const spread = bk.asks[0].price - bk.bids[0].price;
  const dayChg = (s: Sym) => (tick ? all[s][tick] / all[s][tick - 1] - 1 : 0);

  const stat = (label: string, value: string, cls = "") => <div className="stat"><dt>{label}</dt><dd className={cls}>{value}</dd></div>;

  return (
    <div className="ws">
      <div className="simbar" role="note">
        <span className="pill sim">SIMULATION</span>
        <span><strong>Browser simulation.</strong> Prices are seeded random numbers, the order book is generated, and orders match inside your browser. This is not the C++ exchange and not market data. Tickers are labels only.</span>
        <span className="sess" data-state={playing ? "run" : "pause"}><i />{playing ? "Replaying" : "Paused"} · day {tick} of {end}</span>
      </div>

      <div className="col l">
      <section className="panel watch" aria-labelledby="h-watch">
        <h2 id="h-watch">Watchlist</h2>
        <div role="radiogroup" aria-label="Stock" className="wl">
          {SYMBOLS.map((s) => (
            <label key={s} className={s === sym ? "wrow on" : "wrow"}>
              <input type="radio" name="sym" value={s} aria-label={s} checked={s === sym} onChange={() => setSym(s)} />
              <b>{s}</b><span className="num">{marks[s].toFixed(2)}</span>
              <Sparkline values={all[s].slice(Math.max(0, tick - 29), tick + 1)} up={dayChg(s) >= 0} />
              <span className={`num ${pnlClass(dayChg(s))}`}>{dayChg(s) >= 0 ? "+" : ""}{(dayChg(s) * 100).toFixed(2)}%</span>
            </label>
          ))}
        </div>
        <p className="fine">5 synthetic series. Only the ticker names echo real Nasdaq symbols.</p>
      </section>

      <section className="panel ticket" aria-labelledby="h-order">
        <h2 id="h-order">Order ticket · {sym}</h2>
        <form onSubmit={send}>
          <div className="sidebtns" role="radiogroup" aria-label="Side">
            {(["buy", "sell"] as const).map((s) => (
              <label key={s} className={`${s} ${form.side === s ? "on" : ""}`}><input type="radio" name="side" aria-label={s === "buy" ? "Buy" : "Sell"} checked={form.side === s} onChange={() => setForm({ ...form, side: s })} />{s === "buy" ? "Buy" : "Sell"}</label>
            ))}
          </div>
          <Seg name="otype" label="Order type" value={form.type} opts={[["Market", "market"], ["Limit (IOC)", "limit"]]} onChange={(type) => setForm({ ...form, type })} />
          <div className="two">
            <label>Shares<input inputMode="numeric" value={form.qty} onChange={(e) => setForm({ ...form, qty: e.target.value })} /></label>
            <label>Limit price<input inputMode="decimal" disabled={form.type !== "limit"} value={form.limit} placeholder={bk.asks[0].price.toFixed(2)} onChange={(e) => setForm({ ...form, limit: e.target.value })} /></label>
          </div>
          <div className="quick" aria-label="Quick quantity">{[1, 5, 10, 25, 50].map((n) => <button type="button" key={n} className="ghost" onClick={() => setForm({ ...form, qty: String(n) })}>{n}</button>)}</div>
          <dl className="est">
            <div><dt>Reference price</dt><dd>{refPx.toFixed(2)}</dd></div>
            <div><dt>Est. {form.side === "buy" ? "cost" : "proceeds"}</dt><dd>{Number.isFinite(qty) ? usd(qty * refPx) : "—"}</dd></div>
            <div><dt>Buying power</dt><dd>{usd(buyingPower(acct, marks))}</dd></div>
          </dl>
          <p className={`precheck ${preCheck ? "bad" : "ok"}`}>{preCheck ? `Would be rejected: ${preCheck}` : "Passes pre-trade risk checks"}</p>
          <button type="submit" className={`submit ${form.side}`}>Send simulated order</button>
        </form>
        <div className="feedback" role="status" aria-live="polite">
          {last ? (<><span className={`badge ${last.status.replace(" ", "-").toLowerCase()}`}>{last.status}</span> <span>#{last.id} {last.order.side.toUpperCase()} {last.order.qty} {last.order.sym}{last.filled ? ` · filled ${last.filled} @ ${last.avg.toFixed(2)}` : ""}</span><small>{last.status === "Rejected" ? `Rejected: ${last.note}` : last.note}</small></>) : "No orders yet."}
        </div>
        <p className="fine">Risk limits (same as the Python bridge): {LIMITS.maxQty} shares and {usd(LIMITS.maxOrderNotional)} per order, {usd(LIMITS.maxPosition)} per stock, {usd(LIMITS.maxGross)} total exposure, long-only. Limit orders are immediate-or-cancel and never rest on the book.</p>
      </section>

      </div>

      <dl className="acct" aria-label="Account summary">
        {stat("Equity", usd(eq))}{stat("Cash", usd(acct.cash))}{stat("Buying power", usd(buyingPower(acct, marks)))}
        {stat("Positions", usd(mvTotal))}{stat("Unrealized P&L", signed(unreal), pnlClass(unreal))}{stat("Realized P&L", signed(realized), pnlClass(realized))}
        {stat("Total P&L", `${signed(total)} (${((total / LIMITS.startCash) * 100).toFixed(2)}%)`, pnlClass(total))}
      </dl>

      <div className="col c">
      <section className="panel chartp" aria-labelledby="h-chart">
        <div className="bar">
          <h2 id="h-chart">{sym} · synthetic price, day 0 to {tick}</h2>
          <Seg name="tf" label="Bar size" value={tf} opts={TFS} onChange={setTf} />
          <Seg name="range" label="Visible bars" value={range} opts={RANGES} onChange={setRange} />
          <label className="chk"><input type="checkbox" checked={showSma} onChange={(e) => setShowSma(e.target.checked)} />SMA 20</label>
        </div>
        <div className="bar replay" role="group" aria-label="Replay controls">
          <span className="fine">Replay</span>
          <button type="button" className="ghost" disabled={tick >= end} onClick={() => setTick((t) => Math.min(t + 1, end))}>Next day</button>
          <button type="button" className="ghost" aria-pressed={playing} disabled={tick >= end} onClick={() => setPlaying((p) => !p)}>{playing ? "Pause" : "Auto-play"}</button>
          <Seg name="speed" label="Replay speed" value={speed} opts={[["1×", 1], ["2×", 2], ["4×", 4]]} onChange={setSpeed} />
          <span className="grow" />
          <button type="button" className="ghost" onClick={reset}>Reset demo</button>
        </div>
        <CandleChart sym={sym} cs={bars} unit={tf === 1 ? "1 day" : `${tf} days`} showSma={showSma} />
      </section>

            <section className="panel blotter" aria-label="Portfolio and history">
        <div role="tablist" aria-label="Blotter" className="tabs">
          {([["positions", `Positions (${rows.length})`], ["orders", `Orders (${recs.length})`], ["executions", `Executions (${acct.fills.length})`], ["sample", "Scripted sample"]] as const).map(([k, t]) => (
            <button key={k} role="tab" type="button" aria-selected={tab === k} onClick={() => setTab(k)}>{t}</button>
          ))}
        </div>
        <div role="tabpanel" className="scroll" tabIndex={0} aria-label={tab}>
          {tab === "positions" && (!rows.length ? <p className="emptybox">No open positions. Send a buy from the ticket to open one.</p> : (
            <table><caption className="sr">Positions</caption>
              <thead><tr><th scope="col">Symbol</th><th scope="col">Shares</th><th scope="col">Avg cost</th><th scope="col">Last</th><th scope="col">Market value</th><th scope="col">Unrealized P&amp;L</th><th scope="col">Weight</th></tr></thead>
              <tbody>
                {rows.map((r) => <tr key={r.s}><th scope="row">{r.s}</th><td>{r.qty}</td><td>{r.avg.toFixed(2)}</td><td>{marks[r.s].toFixed(2)}</td><td>{usd(r.mv)}</td><td className={pnlClass(r.upl)}>{signed(r.upl)}</td><td>{((r.mv / eq) * 100).toFixed(1)}%</td></tr>)}
              </tbody></table>
          ))}
          {tab === "orders" && (!recs.length ? <p className="emptybox">No orders yet. Rejected and cancelled orders are listed too. Nothing rests on the book: limit orders are immediate-or-cancel.</p> : (
            <table><caption className="sr">Order history, newest first</caption>
              <thead><tr><th scope="col">ID</th><th scope="col">Day</th><th scope="col">Symbol</th><th scope="col">Side</th><th scope="col">Type</th><th scope="col">Qty</th><th scope="col">Limit</th><th scope="col">Filled</th><th scope="col">Avg px</th><th scope="col">Status</th><th scope="col">Detail</th></tr></thead>
              <tbody>
                {recs.map((r) => <tr key={r.id}><td>{r.id}</td><td>{r.tick}</td><th scope="row">{r.order.sym}</th><td className={r.order.side === "buy" ? "up" : "dn"}>{r.order.side}</td><td>{r.order.type === "limit" ? "Limit IOC" : "Market"}</td><td>{r.order.qty}</td><td>{r.order.type === "limit" ? r.order.limit : "—"}</td><td>{r.filled}</td><td>{r.filled ? r.avg.toFixed(2) : "—"}</td><td><span className={`badge ${r.status.replace(" ", "-").toLowerCase()}`}>{r.status}</span></td><td className="detail">{r.note}</td></tr>)}
              </tbody></table>
          ))}
          {tab === "executions" && (!acct.fills.length ? <p className="emptybox">No executions yet.</p> : (
            <table><caption className="sr">Simulated executions, newest first</caption>
              <thead><tr><th scope="col">Exec</th><th scope="col">Day</th><th scope="col">Symbol</th><th scope="col">Side</th><th scope="col">Qty</th><th scope="col">Price</th><th scope="col">Notional</th></tr></thead>
              <tbody>
                {acct.fills.map((f, i) => ({ f, i })).reverse().map(({ f, i }) => <tr key={i}><td>E{i + 1}</td><td>{f.tick}</td><th scope="row">{f.sym}</th><td className={f.side === "buy" ? "up" : "dn"}>{f.side}</td><td>{f.qty}</td><td>{f.price.toFixed(2)}</td><td>{usd(f.qty * f.price)}</td></tr>)}
              </tbody></table>
          ))}
          {tab === "sample" && (
            <>
              <div className="banner" role="note"><strong>Generated demonstration data, not live.</strong> Produced by this page's own browser simulator from seeded random numbers, at day {WARM}: one IOC limit buy of 20 shares per stock at the third ask level. Not output from the C++ exchange and not market data.</div>
              <table><caption className="sr">Planned orders and resulting fills</caption>
                <thead><tr><th scope="col">Stock</th><th scope="col">Planned qty</th><th scope="col">Limit</th><th scope="col">Filled qty</th><th scope="col">Avg fill price</th><th scope="col">Status</th></tr></thead>
                <tbody>{sample.map((r) => <tr key={r.order.sym}><th scope="row">{r.order.sym}</th><td>{r.order.qty}</td><td>{r.order.limit!.toFixed(2)}</td><td>{r.filled}</td><td>{r.filled ? r.avg.toFixed(2) : "-"}</td><td><span className={`badge ${r.status.replace(" ", "-").toLowerCase()}`}>{r.status}</span></td></tr>)}</tbody>
              </table>
            </>
          )}
        </div>
      </section>
      </div>
      <div className="col r">
      <section className="panel bookp" aria-labelledby="h-book">
        <h2 id="h-book">Simulated order book</h2>
        <table className="ladder">
          <caption className="sr">Eight price levels on each side, best prices nearest the spread. Quantities are shares.</caption>
          <thead><tr><th scope="col">Price</th><th scope="col">Size</th><th scope="col">Total</th></tr></thead>
          <tbody>
            {[...bk.asks].reverse().map((l, j) => { const i = 7 - j; return (
              <tr key={`a${i}`} className="ask"><td>{l.price.toFixed(2)}</td><td><span className="fill" style={{ width: `${(l.qty / maxQ) * 100}%` }} />{l.qty}</td><td>{cumA[i]}</td></tr>); })}
            <tr className="spread"><td colSpan={3}>Spread {spread.toFixed(2)} · mid {bk.mid.toFixed(2)}</td></tr>
            {bk.bids.map((l, i) => <tr key={`b${i}`} className="bid"><td>{l.price.toFixed(2)}</td><td><span className="fill" style={{ width: `${(l.qty / maxQ) * 100}%` }} />{l.qty}</td><td>{cumB[i]}</td></tr>)}
          </tbody>
        </table>
        <h3>Market depth</h3>
        <DepthChart bk={bk} />
        <p className="dcap"><span className="up">Bid {bk.bids[7].price.toFixed(2)}–{bk.bids[0].price.toFixed(2)}</span><span className="dn">Ask {bk.asks[0].price.toFixed(2)}–{bk.asks[7].price.toFixed(2)}</span></p>
      </section>

      </div>
    </div>
  );
}
